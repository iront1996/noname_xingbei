'use strict';
const assert=require('node:assert/strict');
const {createSeatRegistry}=require('./seat-registry.js');
let clock=100;
const registry=createSeatRegistry({now:()=>clock,graceMs:10000});
const owner={wsid:'owner'}, room={key:'room-secret',owner};
const guest={wsid:'seat-A',room,owner,onlineKey:'public-key',nickname:'guest',avatar:'a'};
const creds=registry.issue(room,guest);
assert.equal(creds.seatId,'seat-A');
assert.equal(creds.token.length,64);
assert.equal(registry.issue(room,guest),null,'duplicate issue rejected');
const attacker={wsid:'temporary',onlineKey:'public-key'};
assert.equal(registry.adopt(room,attacker,'seat-A','00'.repeat(32)),null,'public id insufficient');
assert.equal(registry.adopt(room,{...attacker,onlineKey:'other'},'seat-A',creds.token),null);
const replacement={wsid:'new-tmp',onlineKey:'public-key'};
const adopted=registry.adopt(room,replacement,'seat-A',creds.token);
assert.equal(adopted.stableSeatId,'seat-A');
assert.equal(adopted.oldSocket,guest);
assert.equal(registry.drop(room,guest),false,'stale socket cannot mark replacement offline');
replacement.wsid='seat-A';replacement.room=room;replacement.owner=owner;
assert.equal(registry.drop(room,replacement),true);
const newcomer={wsid:'temp2',onlineKey:'public-key'};
clock+=9999;
assert.ok(registry.eligible(room,newcomer,'seat-A',creds.token));
clock+=2;
assert.equal(registry.adopt(room,newcomer,'seat-A',creds.token),null,'expired rejected');
assert.equal(registry.adopt({key:'room-secret',owner},newcomer,'seat-A',creds.token),null,'room-scoped');
assert.equal(registry.revoke(room,'seat-A'),true);
assert.equal(registry.adopt(room,newcomer,'seat-A',creds.token),null);
const paused={key:'foo',owner,paused:true};
const c=registry.issue(paused,{wsid:'other',room:paused,owner,onlineKey:'p'});
assert.equal(registry.adopt(paused,{wsid:'tmp',onlineKey:'p'},'other',c.token),null);
console.log('PASS B2 security/seat lifecycle');
