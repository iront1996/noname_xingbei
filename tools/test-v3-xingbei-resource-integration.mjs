import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const get=path=>readFileSync(resolve(root,path),"utf8");
const vault=get("game/v3-recovery-vault.mjs");
const owner=get("game/v3-owner-connection.mjs");
const entry=get("mode/connect.js");
const resources=get("game/v3-xingbei-resource-evidence.mjs");
test("V3 archive is independent of history event checkpoint and genuine skills",()=>{
 assert.match(vault,/buildV3XingbeiResourceEvidence\(/);
 assert.match(vault,/verifyV3XingbeiResourceEvidence\(/);
 assert.match(vault,/XINGBEI_RESOURCE_SUFFIX = "::xingbei-resource-evidence-v1"/);
 assert.match(vault,/saveXingbeiResourceEvidence\(/);
 assert.match(vault,/inspectLocalXingbeiResourceEvidence\(/);
 assert.match(vault,/store\.delete\(roomId \+ XINGBEI_RESOURCE_SUFFIX\)/);
 assert.match(vault,/await resourceWrite/);
 assert.match(vault,/\+":"\+roomId\+":"\+capturedAt/);
 assert.match(vault,/\+":"\+roomId\+":"\+record\.capturedAt/);
 assert.doesNotMatch(resources,/JSON\.stringify\(sample\)/);
 assert.doesNotMatch(resources,/\.hp\b|\.maxHp\b|\.playerid\b/);
 assert.doesNotMatch(resources,/getCards\(|get\.cardsInfo/);
});
test("V21 diagnostic exposes only metadata and never unlocks owner cold resume",()=>{
 assert.match(owner,/inspectLocalXingbeiResourceEvidence/);
 assert.match(owner,/本機加密星杯資源證據/);
 assert.match(owner,/ENCRYPTED_XINGBEI_RESOURCE_VERIFIED/);
 assert.match(owner,/資源證據沒有牌的身分順序/);
 assert.match(owner,/v3-xingbei-resource-evidence-21/);
 assert.match(entry,/v3-xingbei-resource-evidence-21/);
 assert.doesNotMatch(entry,/import\("\/game\/v3-recovery-vault\.mjs/);
 assert.match(owner,/installV3RecoveryVault\(\);/);
 assert.match(vault,/safeCheckpointCertified: false/);
 assert.match(vault,/eventContinuationCaptured: false/);
 assert.match(vault,/restorable: false/);
 assert.doesNotMatch(owner,/game\.send\("server",\s*"v3ready"/);
});
